    public static string Get(string key, string culture)
    {
        var text = Texts[key];
        return culture switch { "zh-Hans" => text.Hans, "zh-Hant" => text.Hant, _ => text.En };
    }

    public static IEnumerable<string> Keys => Texts.Keys;

    public static string Detect(IEnumerable<string> languages)
    {
        foreach (var language in languages)
        {
            var parts = language.ToLowerInvariant().Split('-');
            if (parts[0] == "en")
                return "en";
            if (parts[0] != "zh")
                continue;
            if (parts.Contains("hant"))
                return "zh-Hant";
            if (parts.Contains("hans"))
                return "zh-Hans";
            return parts.Any(part => part is "tw" or "hk" or "mo") ? "zh-Hant" : "zh-Hans";
        }
        return "en";
    }
